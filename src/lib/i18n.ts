export function getDepartments(locale: Locale): string[] {
  return locale === "th" ? DEPARTMENTS_TH : DEPARTMENTS_EN;
}

export function translateDept(name: string | null | undefined, locale: Locale): string | null {
  if (!name) return name ?? null;
  const thIdx = DEPARTMENTS_TH.indexOf(name);
  if (thIdx !== -1) return locale === "th" ? DEPARTMENTS_TH[thIdx] : DEPARTMENTS_EN[thIdx];
  const enIdx = DEPARTMENTS_EN.indexOf(name);
  if (enIdx !== -1) return locale === "th" ? DEPARTMENTS_TH[enIdx] : DEPARTMENTS_EN[enIdx];
  return name;
}
